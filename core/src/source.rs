// The project as files: which files are the project's own code, their text and syntax trees, and positions.
use crate::changes::{Hashes, hash};
use crate::lang::{Import, Lang, lang_for};
use crate::model::Ref;
use std::collections::HashMap;
use std::path::{Path, PathBuf};
use tree_sitter::{Node, Parser, Point, Tree};

pub struct SourceFile {
    pub rel: String,
    pub abs: PathBuf,
    pub text: String,
    pub tree: Tree,
    pub lang: &'static Lang,
    pub imports: Vec<Import>,
    line_starts: Vec<usize>,
}

impl SourceFile {
    pub fn line(&self, row: usize) -> &str {
        let start = self.line_starts[row];
        let end = self.line_starts.get(row + 1).map(|e| e - 1).unwrap_or(self.text.len());
        &self.text[start..end]
    }
    pub fn lines(&self) -> usize {
        self.line_starts.len()
    }
    /// The file says it is made by a tool, not written by hand, in the comments it starts with: "@generated",
    /// "auto-generated", "Code generated by …", or "generated" with "do not edit" or "do not modify".
    pub fn generated(&self) -> bool {
        let head: Vec<String> = (0..self.lines())
            .map(|r| self.line(r).trim())
            .take_while(|t| t.is_empty() || ["//", "#", "/*", "*", "--", "<!--", "\"\"\""].iter().any(|c| t.starts_with(c)))
            .take(20)
            .map(str::to_lowercase)
            .collect();
        let head = head.join(" ");
        ["@generated", "auto-generated", "autogenerated", "automatically generated", "code generated"].iter().any(|m| head.contains(m))
            || (head.contains("generated") && (head.contains("do not edit") || head.contains("do not modify")))
    }
    /// LSP counts columns in UTF-16 code units; tree-sitter in bytes.
    pub fn utf16_col(&self, row: usize, byte_col: usize) -> u32 {
        let line = self.line(row);
        line[..byte_col.min(line.len())].encode_utf16().count() as u32
    }
    pub fn byte_col(&self, row: usize, utf16_col: u32) -> usize {
        let line = self.line(row);
        let mut units = 0u32;
        for (i, ch) in line.char_indices() {
            if units >= utf16_col {
                return i;
            }
            units += ch.len_utf16() as u32;
        }
        line.len()
    }
    /// The smallest named node starting at a position (row, UTF-16 column), as LSP reports it.
    pub fn node_at(&self, row: usize, utf16_col: u32) -> Option<Node<'_>> {
        if row >= self.lines() {
            return None;
        }
        let p = Point { row, column: self.byte_col(row, utf16_col) };
        self.tree.root_node().named_descendant_for_point_range(p, p)
    }
    pub fn text_of(&self, n: Node) -> &str {
        &self.text[n.byte_range()]
    }
    /// The import that gives a name to the whole file.
    pub fn import(&self, local: &str) -> Option<&Import> {
        self.imports.iter().find(|i| i.local == local && i.scope.is_none())
    }
    /// The import a name written at `at` refers to: one in the function or class it is written in (the innermost),
    /// else one that gives it to the whole file.
    pub fn import_at(&self, local: &str, at: Node) -> Option<&Import> {
        let b = at.start_byte();
        let inside = self.imports.iter().filter(|i| i.local == local).filter_map(|i| i.scope.filter(|(s, e)| *s <= b && b < *e).map(|(s, _)| (s, i)));
        inside.max_by_key(|(s, _)| *s).map(|(_, i)| i).or_else(|| self.import(local))
    }
}

pub struct Project {
    pub root: PathBuf,
    pub name: String,
    pub files: Vec<SourceFile>,
    /// the content of every file read, as it was read (also of files that could not be parsed)
    pub hashes: Hashes,
    by_path: HashMap<PathBuf, usize>,
}

/// Directories that hold other people's code or build output, whatever the project's .gitignore says.
pub(crate) const NOT_OWN: &[&str] = &["node_modules", ".git", "site-packages", "__pycache__"];

/// The project's own source files that have a language table, sorted (declaration files left out).
pub(crate) fn own_sources(root: &Path) -> Vec<(PathBuf, &'static Lang)> {
    let walker = ignore::WalkBuilder::new(root)
        .hidden(true)
        .filter_entry(|e| {
            let n = e.file_name().to_string_lossy();
            // a Python environment is a dependency folder whatever it is called
            !(NOT_OWN.contains(&n.as_ref()) || (e.file_type().is_some_and(|t| t.is_dir()) && e.path().join("pyvenv.cfg").exists()))
        })
        .build();
    let mut paths: Vec<PathBuf> = walker.flatten().filter(|e| e.file_type().is_some_and(|t| t.is_file())).map(|e| e.into_path()).collect();
    paths.sort();
    paths
        .into_iter()
        .filter(|p| !p.file_name().is_some_and(|n| n.to_string_lossy().ends_with(".d.ts")))
        .filter_map(|p| lang_for(&p).map(|l| (p, l)))
        .collect()
}

/// A file's path as the model names it: relative to the project root.
pub(crate) fn rel_path(root: &Path, abs: &Path) -> String {
    abs.strip_prefix(root).unwrap_or(abs).to_string_lossy().to_string()
}

/// The language servers a project needs, without parsing it.
pub fn server_kinds(root: &Path) -> std::collections::BTreeSet<&'static str> {
    own_sources(root).into_iter().map(|(_, l)| l.server).collect()
}

impl Project {
    pub fn load(root: &Path) -> std::io::Result<Project> {
        let root = std::fs::canonicalize(root)?;
        let name = root.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
        let mut files = vec![];
        let mut hashes = Hashes::new();
        let mut parsers: HashMap<&str, Parser> = HashMap::new();
        for (abs, lang) in own_sources(&root) {
            let Ok(bytes) = std::fs::read(&abs) else { continue };
            let rel = rel_path(&root, &abs);
            hashes.insert(rel.clone(), hash(&bytes));
            let Ok(text) = String::from_utf8(bytes) else { continue };
            let parser = parsers.entry(lang.id).or_insert_with(|| {
                let mut p = Parser::new();
                p.set_language(&(lang.grammar)()).expect("grammar");
                p
            });
            let Some(tree) = parser.parse(&text, None) else { continue };
            let mut line_starts = vec![0];
            line_starts.extend(text.match_indices('\n').map(|(i, _)| i + 1));
            let imports = (lang.imports)(tree.root_node(), &text);
            files.push(SourceFile { rel, abs, text, tree, lang, imports, line_starts });
        }
        let by_path = files.iter().enumerate().map(|(i, f)| (f.abs.clone(), i)).collect();
        Ok(Project { root, name, files, hashes, by_path })
    }

    pub fn file_index(&self, abs: &Path) -> Option<usize> {
        self.by_path.get(abs).copied().or_else(|| std::fs::canonicalize(abs).ok().and_then(|p| self.by_path.get(&p).copied()))
    }

    pub fn is_own(&self, abs: &Path) -> bool {
        abs.starts_with(&self.root) && !abs.components().any(|c| NOT_OWN.contains(&c.as_os_str().to_string_lossy().as_ref()))
    }

    /// Lines a node covers, 1-based and inclusive; `end` widens the range to another node.
    pub fn ref_of(&self, file: usize, n: Node, end: Option<Node>) -> Ref {
        let end = end.unwrap_or(n);
        // a node that ends at column 0 really ended on the line before
        let mut to = end.end_position().row;
        if end.end_position().column == 0 && to > n.start_position().row {
            to -= 1;
        }
        Ref { file: self.files[file].rel.clone(), from: n.start_position().row + 1, to: to + 1 }
    }
}

/// A node together with the file it is in. Node identity across the walk is (file, byte range, kind).
#[derive(Clone, Copy)]
pub struct At<'p> {
    pub file: usize,
    pub node: Node<'p>,
}

impl<'p> At<'p> {
    pub fn key(&self) -> NodeKey {
        NodeKey { file: self.file, start: self.node.start_byte(), end: self.node.end_byte(), kind: self.node.kind_id() }
    }
}

impl PartialEq for At<'_> {
    fn eq(&self, other: &Self) -> bool {
        self.key() == other.key()
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct NodeKey {
    pub file: usize,
    pub start: usize,
    pub end: usize,
    pub kind: u16,
}

/// Code text on one line, with whitespace runs squeezed, cut at `max` characters (0 = no limit).
pub fn one_line(s: &str, max: usize) -> String {
    use regex::Regex;
    use std::sync::LazyLock;
    static RULES: LazyLock<[(Regex, &str); 5]> = LazyLock::new(|| {
        // a line that starts with `.` goes on with the one before (a chain of calls written down the page)
        [(Regex::new(r"\s*\n\s*(\??\.)").unwrap(), "${1}"), (Regex::new(r"\s*\n\s*").unwrap(), " "), (Regex::new(r"\(\s+").unwrap(), "("), (Regex::new(r"\s+\)").unwrap(), ")"), (Regex::new(r",\s*\)").unwrap(), ")")]
    });
    let mut t = s.to_string();
    for (re, to) in RULES.iter() {
        t = re.replace_all(&t, *to).into_owned();
    }
    let t = t.trim();
    if max > 0 && t.chars().count() > max {
        let cut: String = t.chars().take(max - 1).collect();
        format!("{cut}…")
    } else {
        t.to_string()
    }
}
